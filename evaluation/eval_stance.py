"""Evaluate sentence-level scientific stance predictions against a frozen JSONL set.

This evaluator deliberately separates three things often conflated in a demo:
label quality, evidence-sentence localisation, and calibrated confidence.  It
never calls an LLM itself; prediction files are immutable artefacts generated by
the system under test.  ``--baseline similarity`` supplies a deterministic
lexical-relatedness control, which cannot infer contradiction by design.
"""

from __future__ import annotations

import argparse
import json
import math
import re
from collections import Counter
from pathlib import Path
from typing import Any

LABELS = ("SUPPORT", "CONTRADICT", "NEUTRAL")
DEFAULT_GOLD = Path("evaluation/stance/dev_fixture.jsonl")


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        row = json.loads(line)
        if not isinstance(row, dict) or not row.get("id"):
            raise ValueError(f"{path}:{line_number} requires object id")
        rows.append(row)
    return rows


def _tokens(text: str) -> set[str]:
    latin = re.findall(r"[a-z0-9]+", text.lower())
    han = re.findall(r"[一-鿿]", text)
    return set(latin + han)


def similarity_baseline(rows: list[dict[str, Any]], threshold: float = 0.12) -> list[dict[str, Any]]:
    """A relatedness-only baseline: it can support or abstain, never refute."""
    predictions = []
    for row in rows:
        claim_tokens, evidence_tokens = _tokens(str(row["claim"])), _tokens(str(row["evidence"]))
        score = len(claim_tokens & evidence_tokens) / max(1, len(claim_tokens | evidence_tokens))
        predictions.append(
            {
                "id": row["id"],
                "stance": "SUPPORT" if score >= threshold else "NEUTRAL",
                "confidence": round(score, 6),
                "sentence": "",
                "method": "lexical_similarity_control",
            }
        )
    return predictions


def _f1(tp: int, fp: int, fn: int) -> float:
    denominator = 2 * tp + fp + fn
    return 0.0 if denominator == 0 else 2 * tp / denominator


def _ece(confidence_and_correct: list[tuple[float, bool]], bins: int = 10) -> float:
    if not confidence_and_correct:
        return 0.0
    ece = 0.0
    for bucket in range(bins):
        low, high = bucket / bins, (bucket + 1) / bins
        selected = [(conf, correct) for conf, correct in confidence_and_correct if low <= conf < high or (bucket == bins - 1 and conf == 1)]
        if selected:
            average_confidence = sum(conf for conf, _ in selected) / len(selected)
            accuracy = sum(correct for _, correct in selected) / len(selected)
            ece += len(selected) / len(confidence_and_correct) * abs(accuracy - average_confidence)
    return ece


def evaluate(gold: list[dict[str, Any]], predictions: list[dict[str, Any]]) -> dict[str, Any]:
    """Return label, sentence, and confidence metrics; fail on missing ids."""
    by_id = {str(row["id"]): row for row in predictions}
    gold_ids = {str(row["id"]) for row in gold}
    missing = sorted(gold_ids - set(by_id))
    if missing:
        raise ValueError(f"missing predictions for {len(missing)} ids: {', '.join(missing[:5])}")

    pairs = []
    for row in gold:
        pred = by_id[str(row["id"])]
        label = str(pred.get("stance") or "NEUTRAL").upper()
        if label not in LABELS:
            label = "NEUTRAL"
        try:
            confidence = max(0.0, min(1.0, float(pred.get("confidence", 0.0))))
        except (TypeError, ValueError):
            confidence = 0.0
        pairs.append((row, pred, label, confidence))

    per_label: dict[str, dict[str, float]] = {}
    for label in LABELS:
        tp = sum(1 for row, _pred, predicted, _confidence in pairs if row["label"] == label and predicted == label)
        fp = sum(1 for row, _pred, predicted, _confidence in pairs if row["label"] != label and predicted == label)
        fn = sum(1 for row, _pred, predicted, _confidence in pairs if row["label"] == label and predicted != label)
        per_label[label] = {"precision": 0.0 if tp + fp == 0 else round(tp / (tp + fp), 6), "recall": 0.0 if tp + fn == 0 else round(tp / (tp + fn), 6), "f1": round(_f1(tp, fp, fn), 6)}

    correct = [predicted == row["label"] for row, _pred, predicted, _confidence in pairs]
    sentence_hits = [
        bool(row.get("evidence_sentence")) and str(pred.get("sentence") or "") == str(row.get("evidence_sentence") or "")
        for row, pred, _label, _confidence in pairs
    ]
    brier = sum((confidence - float(is_correct)) ** 2 for (_row, _pred, _label, confidence), is_correct in zip(pairs, correct)) / len(pairs)
    return {
        "samples": len(pairs),
        "label_distribution": dict(Counter(str(row["label"]) for row, _pred, _label, _confidence in pairs)),
        "accuracy": round(sum(correct) / len(correct), 6),
        "macro_f1": round(sum(per_label[label]["f1"] for label in LABELS) / len(LABELS), 6),
        "per_label": per_label,
        "evidence_sentence_exact_match": round(sum(sentence_hits) / max(1, sum(bool(row.get("evidence_sentence")) for row, _pred, _label, _confidence in pairs)), 6),
        "coverage_non_neutral": round(sum(label != "NEUTRAL" for _row, _pred, label, _confidence in pairs) / len(pairs), 6),
        "brier": round(brier, 6),
        "ece_10": round(_ece([(confidence, is_correct) for (_row, _pred, _label, confidence), is_correct in zip(pairs, correct)]), 6),
    }


def run(gold_path: Path, prediction_path: Path | None = None, baseline: str | None = None) -> dict[str, Any]:
    gold = _read_jsonl(gold_path)
    if baseline == "similarity":
        predictions = similarity_baseline(gold)
        method = "lexical_similarity_control"
    elif prediction_path:
        predictions = _read_jsonl(prediction_path)
        method = str(prediction_path)
    else:
        raise ValueError("provide --predictions or --baseline similarity")
    return {"gold": str(gold_path), "method": method, "metrics": evaluate(gold, predictions)}


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate SciScope sentence-level stance predictions")
    parser.add_argument("--gold", type=Path, default=DEFAULT_GOLD)
    parser.add_argument("--predictions", type=Path)
    parser.add_argument("--baseline", choices=["similarity"])
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    report = run(args.gold, args.predictions, args.baseline)
    text = json.dumps(report, ensure_ascii=False, indent=2)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
